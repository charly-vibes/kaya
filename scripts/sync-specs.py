#!/usr/bin/env python3
"""Copy deployed capability specs and their layers into the mdBook.

Purpose: make every capability under `openspec/specs/<capability>/` readable in
the book's Design specs section without maintaining a second copy by hand.
Responsibilities: for each capability directory, concatenate `spec.md` with the
body of `layer.md` (YAML frontmatter stripped) into `docs/src/specs/<cap>.md`.
Rationale: the deployed specs are the source of truth; the book page is a
build artifact refreshed by `just docs`, so drift is impossible by
construction. Capability directory names are trusted (they come from the spec
corpus, not user input).
"""

from __future__ import annotations

import sys
from pathlib import Path

SPECS = Path("openspec/specs")
OUT = Path("docs/src/specs")
MARKER = "<!-- generated by scripts/sync-specs.py; do not edit: run `just specs-docs` -->"


def layer_body(path: Path) -> str:
    """Return the layer document without its leading YAML frontmatter."""
    text = path.read_text(encoding="utf-8")
    if not text.startswith("---\n"):
        return text
    end = text.find("\n---\n", 4)
    if end == -1:
        return text
    return text[end + len("\n---\n") :]


def main() -> int:
    if not SPECS.is_dir():
        print(f"{SPECS} does not exist; nothing to copy", file=sys.stderr)
        return 1
    OUT.mkdir(parents=True, exist_ok=True)

    written: list[str] = []
    for capability in sorted(path for path in SPECS.iterdir() if path.is_dir()):
        spec = capability / "spec.md"
        if not spec.is_file():
            print(f"skipping {capability.name}: no spec.md", file=sys.stderr)
            continue
        page = MARKER + "\n\n" + spec.read_text(encoding="utf-8").rstrip("\n")
        layer = capability / "layer.md"
        if layer.is_file():
            page += (
                "\n\n---\n\n"
                f"*The rest of this page is the specodelic layer sidecar for this\n"
                f"capability, copied from `openspec/specs/{capability.name}/layer.md`.*\n\n"
                + layer_body(layer).strip("\n")
            )
        (OUT / f"{capability.name}.md").write_text(page + "\n", encoding="utf-8")
        written.append(capability.name)

    # Pages are owned by this script; a page whose capability disappeared is
    # stale. Unmarked files are never touched, so authored notes survive.
    expected = {f"{name}.md" for name in written}
    for existing in sorted(OUT.glob("*.md")):
        if existing.name in expected:
            continue
        if existing.read_text(encoding="utf-8").startswith(MARKER):
            existing.unlink()
            print(f"removed stale page {existing}")

    print(f"wrote {len(written)} spec page(s): {', '.join(written)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())